spoon.MicMute.hotkey.tags = { "mic mute", "microphone", "audio" }
spoon.MicMute:bindVisibilitySetter(function(muted)
  spoon.MicMute.mute_menu:setTitle(nil)
  spoon.MicMute.mute_menu:setIcon(muted and micMuted or micOn)
end)
